GROUP_RULES_FUNCTION = """
CREATE FUNCTION enforce_group_rules() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    group_event integer;
    members integer;
BEGIN
    IF NEW.group_id IS NULL OR NEW.membership = 'declined' THEN
        RETURN NEW;
    END IF;

    -- Lock the group row: with several API pods, two students joining at once would
    -- otherwise both see 3 members and make a group of 5. The second one waits here.
    SELECT event_id INTO group_event FROM buddy_groups WHERE id = NEW.group_id FOR UPDATE;
    IF group_event IS DISTINCT FROM NEW.event_id THEN
        RAISE EXCEPTION 'group % is not a group for event %', NEW.group_id, NEW.event_id
            USING ERRCODE = 'check_violation';
    END IF;

    SELECT count(*) INTO members FROM optins
    WHERE group_id = NEW.group_id AND membership <> 'declined' AND id <> NEW.id;
    IF members >= 4 THEN
        RAISE EXCEPTION 'group % is full', NEW.group_id USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END $$;
"""

GROUP_RULES_TRIGGER = """
CREATE TRIGGER optins_group_rules
BEFORE INSERT OR UPDATE OF group_id, membership, event_id ON optins
FOR EACH ROW EXECUTE FUNCTION enforce_group_rules();
"""

# Per-event counts for the staff stats page. bf_analytics can read only this view, not the tables.
EVENT_STATS_VIEW = """
CREATE VIEW event_stats AS
SELECT
    e.id AS event_id,
    e.title,
    e.starts_at,
    (SELECT count(*) FROM tickets t WHERE t.event_id = e.id) AS ticket_count,
    (SELECT count(*) FROM optins o WHERE o.event_id = e.id) AS optin_count,
    (SELECT count(*) FROM optins o WHERE o.event_id = e.id AND o.group_id IS NULL) AS looking_count,
    (SELECT count(*) FROM buddy_groups g WHERE g.event_id = e.id) AS group_count
FROM events e;
"""

